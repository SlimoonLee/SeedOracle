        cards.Select(ForecastItemDetails.Card).ToList();

    private static CardCreationOptions CardOptions(CardPoolModel pool) => new(
        [pool], CardCreationSource.Other, CardRarityOddsType.Blitz);

    private static CardCreationOptions RareOptions(CardPoolModel pool) => new(
        [pool], CardCreationSource.Other, CardRarityOddsType.Blitz,
        card => card.Rarity == CardRarity.Rare);

    /// <summary>UpgradedRareCard's exact options: Uniform odds over the rare
    /// filter, no upgrade roll — the game's own construction, one draw total.</summary>
    private static CardCreationOptions UniformRareOptions(CardPoolModel pool) =>
        new CardCreationOptions(
            new List<CardPoolModel> { pool }, CardCreationSource.Other,
            CardRarityOddsType.Uniform, card => card.Rarity == CardRarity.Rare)
        .WithFlags(CardCreationFlags.NoUpgradeRoll);

    private static CardCreationOptions UniformOptions(CardPoolModel pool, CardRarity rarity) =>
        CardCreationOptions.ForNonCombatWithUniformOdds([pool], card => card.Rarity == rarity)
            .WithFlags(CardCreationFlags.NoRarityModification);

    private CardPoolModel PrismaticPool(BlitzMerchantEntry entry) =>
        PrismaticCharacterField?.GetValue(entry) is CharacterModel character ? character.CardPool : Pool();

    private (EnchantmentModel, int)? EnchantmentOf(BlitzMerchantEntry entry) =>
        entry is BlitzMerchantCardEnchantEntry
        && EnchantField?.GetValue(entry) is (EnchantmentModel model, int amount)
            ? (model, amount)
            : null;

    private ForecastItemDetails Curse(Rng shops) => ForecastItemDetails.Card(RollCurse(shops));

    /// <summary>The curse pool GiveCurse draws from, queried read-only.</summary>
    private CardModel RollCurse(Rng shops)
    {
        var pool = ModelDb.CardPool<CurseCardPool>()
            .GetUnlockedCards(_player.UnlockState, _player.RunState.CardMultiplayerConstraint)
            .Where(card => card.CanBeGeneratedByModifiers && card.IsAllowedInRun(_player.RunState))
            .OrderBy(card => card.Id)
            .ToList();
        // A non-empty curse pool is a game invariant; the annotation just
        // matches NextItem's nullable signature.
        return shops.NextItem(pool)!;
    }

    /// <summary>
    /// The factory falls back through rarities to Circlet, so the pull always
    /// answers; the annotation just matches its nullable signature.
    /// </summary>
    private RelicModel PullRelic(Rng shops) =>
        RelicFactory.PullNextRelicFromBack(_player, RelicFactory.RollRarity(shops), static _ => true)!;

    /// <summary>
    /// Every candidate the selection would accept, with what it turns into —
    /// each drawn from the same stream position, so the only per-candidate
    /// difference is the self-exclusion. Origins ride along for the paths.
    /// </summary>
    /// <summary>The last transform draw that failed and why, for diagnostics.</summary>
    internal static string? LastTransformError { get; private set; }

    private IReadOnlyList<BlitzCardChoiceOutcome> TransformTable(
        IEnumerable<(CardModel Card, string Origin, int[] Via)> candidates, Rng transformStream)
    {
        var outcomes = new List<BlitzCardChoiceOutcome>();
        foreach (var candidate in candidates)
        {
            try
            {
                var result = CardAddedToDeck(CardFactory.CreateRandomCardForTransform(
                    candidate.Card, isInCombat: false, new Rng(transformStream.ToSerializable())));

                outcomes.Add(new BlitzCardChoiceOutcome(
                    ForecastItemDetails.Card(candidate.Card), ForecastItemDetails.Card(result))
                {
                    Origin = candidate.Origin,
                    ViaSlots = candidate.Via
                });
            }
            catch (Exception error)
            {
                // A pool that cannot offer a replacement is the game's problem;
                // remember the first one so the self-test can say why.
                LastTransformError ??= candidate.Card.GetType().Name + ": "
                    + error.GetBaseException().GetType().Name + " "
                    + error.GetBaseException().Message;
            }
        }
        return outcomes;
    }
