/// <summary>
/// Prices Blitz shop goods straight off the RNG sequences: every entry type
/// moves the streams by a fixed amount (measured, not assumed), so a good's
/// contents after a set of earlier purchases are generated by cloning the
/// streams, skipping ahead by the summed offsets and running the game's own
/// factories at that position. No purchase is ever executed — the shadow
/// graph exists only as read-only context for pool lookups and hooks, so no
/// card previews, vfx nodes or synchronizer events can leak anywhere.
/// </summary>
internal sealed class BlitzShopPreview
{
    private const int TargetRank = int.MaxValue;

    private static readonly FieldInfo? PrismaticCharacterField = typeof(BlitzMerchantPrismaticCardRewardEntry)
        .GetField("_character", BindingFlags.Instance | BindingFlags.NonPublic);

    private static readonly FieldInfo? EnchantField = typeof(BlitzMerchantCardEnchantEntry)
        .GetField("_enchantment", BindingFlags.Instance | BindingFlags.NonPublic);

    private readonly PlanningPredictionService.State _state;
    private readonly Player _player;
    private readonly SerializableRng _shops;
    private readonly SerializableRng _rewards;
    private readonly SerializableRng _transformations;
    private readonly SerializableRelicGrabBag _sharedBag;
    private readonly SerializableRelicGrabBag _playerBag;
    private readonly List<CardModel> _deck;

    /// <summary>The deck the preview prices against, for parity diagnostics.</summary>
    internal IReadOnlyList<CardModel> DeckSnapshot => _deck;
    private readonly int _currentHp;
    private readonly int _maxHp;

    /// <summary>
    /// Stream consumption per entry type, measured by running this same
    /// generator once at offset zero and reading the cloned counters — the
    /// ground truth for every later offset, hooks included.
    /// </summary>
    private readonly Dictionary<BlitzMerchantEntryType, (int Shops, int Rewards)> _deltas = [];

    internal BlitzShopPreview(PlanningPredictionService service, RunState liveRun, Player livePlayer)
    {
        _state = service.CreateState(liveRun, livePlayer);
        _player = _state.Player;
        _shops = _player.PlayerRng.Shops.ToSerializable();
        _rewards = _player.PlayerRng.Rewards.ToSerializable();
        _transformations = _player.PlayerRng.Transformations.ToSerializable();
        _sharedBag = _state.Run.SharedRelicGrabBag.ToSerializable();
        _playerBag = _player.RelicGrabBag.ToSerializable();
        _deck = _player.Deck.Cards.ToList();
        _currentHp = _player.Creature.CurrentHp;
        _maxHp = _player.Creature.MaxHp;
    }

    internal void MeasureDeltas(MerchantInventory inventory)
    {
        foreach (var entry in inventory.BlitzEntries.Where(entry => entry.IsStocked))
        {
            if (_deltas.ContainsKey(entry.MerchantEntryType)) continue;
            var shops = At(_shops, 0);
            var rewards = At(_rewards, 0);
            Generate(entry, shops, rewards, _deck);
            _deltas[entry.MerchantEntryType] = (
                shops.ToSerializable().counter - _shops.counter,
                rewards.ToSerializable().counter - _rewards.counter);
        }
        Reset();
    }

    internal (int Shops, int Rewards) Delta(BlitzMerchantEntryType type) =>
        _deltas.TryGetValue(type, out var delta) ? delta : (0, 0);

    /// <summary>
    /// The good's contents when exactly this set of goods was bought before
    /// it, replayed in shelf order: predecessors drain the shared bag at
    /// their rolled rarities, curses they hand over join the deck, and the
    /// good itself generates at the summed stream offset.
    /// </summary>
    internal BlitzYieldForecast Preview(MerchantInventory inventory, int slot, IReadOnlyList<int> prefix)
    {
        try
        {
            Reset();
            var deck = _deck;
            // Transform candidates tagged with how they become available:
            // already in the library, offered by an earlier buy's reward
            // screen, or handed over as a curse by an earlier buy.
            var candidates = _deck
                .Where(card => card.IsTransformable)
                .Select(card => (Card: card, Origin: "deck", Via: Array.Empty<int>()))
                .ToList();
            var transformSkip = 0;
            var deckBranches = inventory.BlitzEntries[slot].MerchantEntryType
                == BlitzMerchantEntryType.RandomUpgrades
                ? new List<DeckBranchState>
                {
                    new(CloneDeck(_deck), [])
                }
                : null;
            foreach (var before in prefix.OrderBy(other => other))
            {
                var entry = inventory.BlitzEntries[before];
                var offset = OffsetOf(inventory, prefix, before);
                // Generating the predecessor at its own offset IS its replay:
                // same draws, same curse into the deck, same relic pulls.
                var replay = Generate(entry,
                    At(_shops, offset), At(_rewards, offset), deck,
                    rewardSourceSlot: before);
                if (deckBranches is not null)
                    deckBranches = AdvanceDeckBranches(
                        deckBranches, entry, replay, before, transformSkip);
                foreach (var gained in replay.GainedModels)
                {
                    // Pool-canonical cards (curses) reject even an Owner read
                    // (AssertMutable); materialize them the way
                    // AddCursesToDeck would before they join the deck.
                    var owned = gained.IsMutable ? gained : _state.Run.CreateCard(gained, _player);
                    deck = [.. deck, owned];
                    if (owned.IsTransformable)
                        candidates.Add((owned, "curse", [before]));
                }
                foreach (var offered in replay.ScreenModels)
                {
                    var effective = CardAddedToDeck(offered);
                    if (effective.IsTransformable)
                        candidates.Add((effective, "reward", [before]));
                }
                // Each completed transform draws the transformation stream
                // once, so a later transform reads one position further.
                if (entry.MerchantEntryType == BlitzMerchantEntryType.CardTransform)
                    transformSkip++;
            }

            var shops = At(_shops, OffsetOf(inventory, prefix, TargetRank));
            var rewards = At(_rewards, RewardsOffsetOf(inventory, prefix, TargetRank));
            return Generate(inventory.BlitzEntries[slot], shops, rewards, deck,
                candidates, transformSkip, priorDeckBranches: deckBranches).Yield;
        }
        catch (Exception error)
        {
            var root = error.GetBaseException();
            LastTransformError ??= "preview: " + root.GetType().Name + " " + root.Message + " | "
                + string.Join(" <- ", (root.StackTrace ?? "").Split('\n').Take(6).Select(line => line.Trim()));
            return BlitzYieldForecast.Empty;
        }
    }

    /// <summary>
    /// How far the streams sit when this member of the replay buys. The good
    /// itself is always last, so its rank is past every shelf slot.
    /// </summary>
    private int OffsetOf(MerchantInventory inventory, IReadOnlyList<int> prefix, int rank) =>
        prefix.Where(before => before < rank)
            .Sum(before => Delta(inventory.BlitzEntries[before].MerchantEntryType).Shops);

    private int RewardsOffsetOf(MerchantInventory inventory, IReadOnlyList<int> prefix, int rank) =>
        prefix.Where(before => before < rank)
            .Sum(before => Delta(inventory.BlitzEntries[before].MerchantEntryType).Rewards);

    /// <summary>
    /// A clone of a stream, positioned by skipping exactly the draws the
    /// predecessors consumed. MegaRandom advances once per Rng call, so
    /// skipping N draws reaches the state any N real draws would.
    /// </summary>
    private static Rng At(SerializableRng stream, int skip)
    {
        var rng = new Rng(stream);
        for (var drawn = 0; drawn < skip; drawn++) rng.NextUnsignedLong();
        return rng;
    }

    /// <summary>Bags back to capture state; each row replays from scratch.</summary>
    private void Reset()
    {
        _state.Run.SharedRelicGrabBag.LoadFromSerializable(_sharedBag);
        _player.RelicGrabBag.LoadFromSerializable(_playerBag);
    }

    // ---- per-type generation, mirroring each entry's OnTrySelect ----

    /// <summary>
    /// One generation pass: the yield the good hands over, plus the raw card
    /// models behind it — screen cards are candidates a later transform could
    /// act on, gained models are what joins the deck (curses, granted cards).
    /// </summary>
    private sealed record RewardScreen(
        int SourceSlot,
        int ScreenIndex,
        IReadOnlyList<CardModel> Cards);

    private sealed record DeckBranchState(
        List<CardModel> Deck,
        List<BlitzRandomUpgradeChoice> Choices);

    private sealed record Generation(
        BlitzYieldForecast Yield,
        List<CardModel> ScreenModels,
        List<CardModel> GainedModels)
    {
        internal IReadOnlyList<RewardScreen> RewardScreens { get; init; } = [];
    }

    private Generation Generate(
        BlitzMerchantEntry entry,
        Rng shops,
        Rng rewards,
        IReadOnlyList<CardModel> deck,
        IReadOnlyList<(CardModel Card, string Origin, int[] Via)>? transformCandidates = null,
        int transformSkip = 0,
        int rewardSourceSlot = -1,
        IReadOnlyList<DeckBranchState>? priorDeckBranches = null)
    {
        var screens = new List<IReadOnlyList<ForecastItemDetails>>();
        var screenModels = new List<CardModel>();
        var rewardScreens = new List<RewardScreen>();
        var gained = new List<ForecastItemDetails>();
        var gainedModels = new List<CardModel>();
        var upgraded = new List<ForecastItemDetails>();
        var relics = new List<ForecastItemDetails>();
        var potions = new List<ForecastItemDetails>();
        var randomUpgradeVariants = new List<BlitzRandomUpgradeVariant>();

        void ScreenCards(List<CardModel> models)
        {
            screenModels.AddRange(models);
            screens.Add(Described(models));
            if (rewardSourceSlot >= 0)
                rewardScreens.Add(new RewardScreen(
                    rewardSourceSlot, screens.Count - 1, models.ToArray()));
        }

        void Gain(CardModel model)
        {
            gained.Add(ForecastItemDetails.Card(model));
            gainedModels.Add(model);
        }

        switch (entry.MerchantEntryType)
        {
            case BlitzMerchantEntryType.CardRewards:
                ScreenCards(Screen(CardOptions(Pool()), shops));
                ScreenCards(Screen(CardOptions(Pool()), shops));
                break;
            case BlitzMerchantEntryType.UpgradedCardReward:
                // The entry offers ONE screen (a single CardReward) with
                // upgrade rolls suppressed, then upgrades the cards in place.
                var plainOptions = CardOptions(Pool()).WithFlags(CardCreationFlags.NoUpgrades);
                var upgradedOnce = Screen(plainOptions, shops);
                foreach (var card in upgradedOnce) CardCmd.Upgrade(card);
                ScreenCards(upgradedOnce);
                break;
            case BlitzMerchantEntryType.RareCardReward:
                ScreenCards(Screen(RareOptions(Pool()), shops));
                break;
            case BlitzMerchantEntryType.UpgradedRareCardReward:
                Gain(RollCurse(shops));
                var upgradedScreen = Screen(RareOptions(Pool()), shops);
                foreach (var card in upgradedScreen) CardCmd.Upgrade(card);
                ScreenCards(upgradedScreen);
                break;
            case BlitzMerchantEntryType.UpgradedRareCard:
                // The entry uses Uniform odds (no rarity roll — one draw for
                // the card itself) on the SHOPS stream; Blitz odds here would
                // add a rarity draw, and a missing override would silently
                // read the Rewards stream instead — both drifted every later
                // good's position.
                var single = CardFactory.CreateForReward(_player, 1,
                        UniformRareOptions(Pool()).WithRngOverride(shops))
                    .Select(result => result.Card).ToList();
                foreach (var card in single) CardCmd.Upgrade(card);
                foreach (var card in single) Gain(card);
                break;
            case BlitzMerchantEntryType.ColorlessCardReward:
                ScreenCards(Screen(CardOptions(ModelDb.CardPool<ColorlessCardPool>()), shops));
                break;
            case BlitzMerchantEntryType.PrismaticCardReward:
                ScreenCards(Screen(CardOptions(PrismaticPool(entry)), shops));
                break;
            case BlitzMerchantEntryType.EnchantedCardReward:
                var enchanted = Screen(CardOptions(Pool()), shops);
                foreach (var card in enchanted)
                    if (card.Enchantment is null)
                    {
                        var enchant = shops.NextItem(BlitzRunModel.shopEnchantmentOptions
                            .Where(option => option.Item1.CanEnchant(card)));
                        CardCmd.Enchant(enchant.Item1.ToMutable(), card, enchant.Item2);
                    }
                ScreenCards(enchanted);
                break;
            case BlitzMerchantEntryType.CardRewardOfEachRarity:
                Gain(RollCurse(shops));
                foreach (var rarity in new[] { CardRarity.Common, CardRarity.Uncommon, CardRarity.Rare })
                    ScreenCards(Screen(UniformOptions(Pool(), rarity), rewards));
                break;
            case BlitzMerchantEntryType.Potions:
                for (var drawn = 0; drawn < 2; drawn++)
                    potions.Add(ForecastItemDetails.Potion(
                        PotionFactory.CreateRandomPotionOutOfCombat(_player, shops).ToMutable()));
                break;
            case BlitzMerchantEntryType.Relic:
                relics.Add(ForecastItemDetails.Relic(PullRelic(shops)));
                break;
            case BlitzMerchantEntryType.TwoRelics:
                Gain(RollCurse(shops));
                for (var pulled = 0; pulled < 2; pulled++)
                    relics.Add(ForecastItemDetails.Relic(PullRelic(shops)));
                break;
            case BlitzMerchantEntryType.TwoMoreChoices:
                Gain(RollCurse(shops));
                return new Generation(new BlitzYieldForecast
                {
                    Resolved = true, Purchased = true, GainedCards = gained, ExtraChoices = 2
                }, screenModels, gainedModels);
            case BlitzMerchantEntryType.FullHealAndMaxHp:
                Gain(RollCurse(shops));
                return new Generation(new BlitzYieldForecast
                {
                    Resolved = true, Purchased = true, GainedCards = gained,
                    MaxHpDelta = 6, HealedHp = _maxHp + 6 - _currentHp
                }, screenModels, gainedModels);
            case BlitzMerchantEntryType.RandomUpgrades:
                // The game filters the deck to upgradable cards FIRST, then
                // shuffles that list — shuffling the whole deck (curses
                // included) lands the same draw on different cards. The game
                // upgrades the two picks in place; the prediction shows the
                // upgraded names WITHOUT mutating the preview clone's deck.
                var shopsBeforeUpgrade = shops.ToSerializable();
                var shuffled = deck.Where(card => card.IsUpgradable).ToList();
                shuffled.StableShuffle(shops);
                foreach (var pick in shuffled.Take(2))
                {
                    var previewCard = _state.Run.CloneCard(pick);
                    CardCmd.Upgrade(previewCard);
                    upgraded.Add(ForecastItemDetails.Card(previewCard));
                }
                if (priorDeckBranches is { Count: > 0 })
                    randomUpgradeVariants.AddRange(
                        BuildRandomUpgradeVariants(priorDeckBranches, shopsBeforeUpgrade));
                break;
            default:
                return PickNeeding(entry, deck, shops, transformCandidates, transformSkip);
        }

        return new Generation(new BlitzYieldForecast
        {
            Resolved = true,
            Purchased = true,
            CardScreens = screens,
            GainedCards = gained,
            UpgradedCards = upgraded,
            RandomUpgradeVariants = randomUpgradeVariants,
            Relics = relics,
            Potions = potions
        }, screenModels, gainedModels)
        {
            RewardScreens = rewardScreens
        };
    }

    private const int MaxRandomUpgradeVariants = 32;

    /// <summary>
    /// Carry the deck-changing choices of a completed predecessor forward. A
    /// reward pick, removal, transform, upgrade or enchant changes the deck
    /// read by a later good, while none of those choices advances Shops.
    /// </summary>
    private List<DeckBranchState> AdvanceDeckBranches(
        IReadOnlyList<DeckBranchState> input,
        BlitzMerchantEntry entry,
        Generation replay,
        int sourceSlot,
        int transformSkip)
    {
        var states = input.Select(state =>
        {
            var deck = state.Deck.ToList();
            foreach (var gained in replay.GainedModels)
                deck.Add(CloneForBranch(gained));
            return new DeckBranchState(deck, new List<BlitzRandomUpgradeChoice>(state.Choices));
        }).ToList();

        foreach (var screen in replay.RewardScreens
                     .OrderBy(screen => screen.SourceSlot)
                     .ThenBy(screen => screen.ScreenIndex))
        {
            var next = new List<DeckBranchState>();
            foreach (var state in states)
            {
                var skippedChoices = new List<BlitzRandomUpgradeChoice>(state.Choices)
                {
                    new(screen.SourceSlot, screen.ScreenIndex, null)
                };
                next.Add(new DeckBranchState(state.Deck, skippedChoices));

                foreach (var card in screen.Cards)
                {
                    var effective = CardAddedToDeck(card);
                    var selected = new List<CardModel>(state.Deck) { effective };
                    var choices = new List<BlitzRandomUpgradeChoice>(state.Choices)
                    {
                        new(
                            screen.SourceSlot,
                            screen.ScreenIndex,
                            ForecastItemDetails.Card(effective))
                    };
                    next.Add(new DeckBranchState(selected, choices));
                    if (next.Count >= MaxRandomUpgradeVariants) break;
                }

                if (next.Count >= MaxRandomUpgradeVariants) break;
            }

            states = next.Take(MaxRandomUpgradeVariants).ToList();
        }

        return entry.MerchantEntryType switch
        {
            BlitzMerchantEntryType.CardRemoval => ExpandCardRemoval(states, sourceSlot),
            BlitzMerchantEntryType.CardTransform => ExpandCardTransform(states, sourceSlot, transformSkip),
            BlitzMerchantEntryType.CardUpgrade => ExpandCardUpgrade(states, sourceSlot),
            BlitzMerchantEntryType.CardEnchant => ExpandCardEnchant(states, sourceSlot, entry),
            _ => states
        };
    }

    private List<DeckBranchState> ExpandCardRemoval(
        IReadOnlyList<DeckBranchState> states,
        int sourceSlot)
    {
        var next = new List<DeckBranchState>();
        foreach (var state in states)
        {
            foreach (var card in state.Deck.Where(card => card.IsRemovable).ToList())
            {
                var deck = state.Deck.ToList();
                deck.RemoveAt(deck.FindIndex(candidate => ReferenceEquals(candidate, card)));
                var choices = new List<BlitzRandomUpgradeChoice>(state.Choices)
                {
                    new(sourceSlot, -1, ForecastItemDetails.Card(card),
                        Kind: BlitzRandomUpgradeChoiceKind.Remove)
                };
                next.Add(new DeckBranchState(deck, choices));
                if (next.Count >= MaxRandomUpgradeVariants) return next;
            }
        }
        return next;
    }

    private List<DeckBranchState> ExpandCardTransform(
        IReadOnlyList<DeckBranchState> states,
        int sourceSlot,
        int transformSkip)
    {
        var next = new List<DeckBranchState>();
        foreach (var state in states)
        {
            foreach (var card in state.Deck.Where(card => card.IsTransformable).ToList())
            {
                CardModel result;
                try
                {
                    var transformRng = At(_transformations, transformSkip);
                    result = CardAddedToDeck(CardFactory.CreateRandomCardForTransform(
                        card, isInCombat: false,
                        new Rng(transformRng.ToSerializable())));
                }
                catch (Exception)
                {
                    continue;
                }

                var deck = state.Deck.ToList();
                deck[deck.FindIndex(candidate => ReferenceEquals(candidate, card))] = result;
                var choices = new List<BlitzRandomUpgradeChoice>(state.Choices)
                {
                    new(sourceSlot, -1, ForecastItemDetails.Card(card),
                        ForecastItemDetails.Card(result), BlitzRandomUpgradeChoiceKind.Transform)
                };
                next.Add(new DeckBranchState(deck, choices));
                if (next.Count >= MaxRandomUpgradeVariants) return next;
            }
        }
        return next;
    }

    private List<DeckBranchState> ExpandCardUpgrade(
        IReadOnlyList<DeckBranchState> states,
        int sourceSlot)
    {
        var next = new List<DeckBranchState>();
        foreach (var state in states)
        {
            foreach (var card in state.Deck.Where(card => card.IsUpgradable).ToList())
            {
                var upgraded = CloneForBranch(card);
                CardCmd.Upgrade(upgraded);
                var deck = state.Deck.ToList();
                deck[deck.FindIndex(candidate => ReferenceEquals(candidate, card))] = upgraded;
                var choices = new List<BlitzRandomUpgradeChoice>(state.Choices)
                {
                    new(sourceSlot, -1, ForecastItemDetails.Card(card),
                        ForecastItemDetails.Card(upgraded), BlitzRandomUpgradeChoiceKind.Upgrade)
                };
                next.Add(new DeckBranchState(deck, choices));
                if (next.Count >= MaxRandomUpgradeVariants) return next;
            }
        }
        return next;
    }

    private List<DeckBranchState> ExpandCardEnchant(
        IReadOnlyList<DeckBranchState> states,
        int sourceSlot,
        BlitzMerchantEntry entry)
    {
        var enchantment = EnchantmentOf(entry);
        if (enchantment is null) return [];

        var next = new List<DeckBranchState>();
        foreach (var state in states)
        {
            foreach (var card in state.Deck.Where(card => enchantment.Value.Item1.CanEnchant(card)).ToList())
            {
                var enchanted = CloneForBranch(card);
                CardCmd.Enchant(enchantment.Value.Item1.ToMutable(), enchanted, enchantment.Value.Item2);
                var deck = state.Deck.ToList();
                deck[deck.FindIndex(candidate => ReferenceEquals(candidate, card))] = enchanted;
                var choices = new List<BlitzRandomUpgradeChoice>(state.Choices)
                {
                    new(sourceSlot, -1, ForecastItemDetails.Card(card),
                        ForecastItemDetails.Card(enchanted), BlitzRandomUpgradeChoiceKind.Enchant)
                };
                next.Add(new DeckBranchState(deck, choices));
                if (next.Count >= MaxRandomUpgradeVariants) return next;
            }
        }
        return next;
    }

    private IReadOnlyList<BlitzRandomUpgradeVariant> BuildRandomUpgradeVariants(
        IReadOnlyList<DeckBranchState> states,
        SerializableRng shopsBefore)
    {
        var variants = new List<BlitzRandomUpgradeVariant>(states.Count);
        foreach (var state in states)
        {
            var branchRng = new Rng(shopsBefore);
            var shuffled = state.Deck.Where(card => card.IsUpgradable).ToList();
            shuffled.StableShuffle(branchRng);
            var branchUpgrades = shuffled.Take(2)
                .Select(card =>
                {
                    var previewCard = _state.Run.CloneCard(card);
                    CardCmd.Upgrade(previewCard);
                    return ForecastItemDetails.Card(previewCard);
                })
                .ToList();
            variants.Add(new BlitzRandomUpgradeVariant(state.Choices, branchUpgrades));
        }

        return variants;
    }

    private List<CardModel> CloneDeck(IEnumerable<CardModel> cards) =>
        cards.Select(CloneForBranch).ToList();

    private CardModel CloneForBranch(CardModel card) =>
        card.IsMutable ? _state.Run.CloneCard(card) : _state.Run.CreateCard(card, _player);

    /// <summary>
    /// CardPileCmd.Add and CardCmd.Transform both run the deck-add hooks after
    /// the generated card is chosen. This covers the three Egg relics and
    /// other add-time relics such as Fresnel Lens without consuming a stream.
    /// </summary>
    private CardModel CardAddedToDeck(CardModel card)
    {
        var owned = CloneForBranch(card);
        return Hook.ModifyCardBeingAddedToDeck(_state.Run, owned, out _);
    }

    private Generation PickNeeding(
        BlitzMerchantEntry entry,
        IReadOnlyList<CardModel> deck,
        Rng shops,
        IReadOnlyList<(CardModel Card, string Origin, int[] Via)>? transformCandidates,
        int transformSkip)
    {
        var pickable = 0;
        IReadOnlyList<BlitzCardChoiceOutcome> transformChoices = [];
        var gained = new List<ForecastItemDetails>();
        var gainedModels = new List<CardModel>();
        switch (entry.MerchantEntryType)
        {
            case BlitzMerchantEntryType.CardTransform:
                pickable = deck.Count(card => card.IsTransformable);
                // The full candidate set — library, earlier rewards, earlier
                // curses — each tagged with how it becomes available, so the
                // window can answer "which way gets this result".
                transformChoices = TransformTable(
                    transformCandidates ?? deck.Where(card => card.IsTransformable)
                        .Select(card => (card, "deck", Array.Empty<int>())),
                    At(_transformations, transformSkip));
                break;
            case BlitzMerchantEntryType.CardUpgrade:
                pickable = deck.Count(card => card.IsUpgradable);
                break;
            case BlitzMerchantEntryType.CardRemoval:
                // Unremovable cards (Eternal, e.g. AscendersBane) are excluded
                // by the game's own removal selection.
                pickable = deck.Count(card => card.IsRemovable);
                break;
            case BlitzMerchantEntryType.CardEnchant:
                pickable = deck.Count(card => EnchantmentOf(entry) is { } enchant
                    && enchant.Item1.CanEnchant(card));
                break;
            case BlitzMerchantEntryType.Glam:
                pickable = deck.Count(card => ModelDb.Enchantment<Glam>().CanEnchant(card));
                // The curse lands only after a completed pick, so the display
                // yield stays clean for the declined-probe comparison — but
                // the replay (gainedModels) still draws it: a completed Glam
                // predecessor moves the stream by exactly this curse.
                var curse = RollCurse(shops);
                gainedModels.Add(curse);
                break;
            default:
                return new Generation(BlitzYieldForecast.Empty, [], []);
        }
        return new Generation(new BlitzYieldForecast
        {
            Resolved = true,
            Purchased = true,
            NeedsCardPick = true,
            PickableCards = pickable,
            TransformChoices = transformChoices,
            GainedCards = gained
        }, [], gainedModels);
    }

    /// <summary>
    /// One 3-card screen as the game generates it — CardModels, so later
    /// rolls (upgrades, enchants) still touch the same instances.
    /// </summary>
    private List<CardModel> Screen(CardCreationOptions options, Rng shops)
    {
        var reward = new CardReward(options.WithRngOverride(shops), 3, _player);
        reward.Populate();
        return reward.Cards.ToList();
    }

    private CardPoolModel Pool() => _player.Character.CardPool;

